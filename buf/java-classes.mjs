// Finds the Java classes that two proto files of one service would both generate.
//
// Java services compile a service's published proto jar with protoc's Java generator, which names
// each file's outer class after the file name (getMessageById.proto → GetMessageById) inside the
// file's java_package, or its proto package when that is unset. Two files with one name in one
// package therefore write the same class, and every Java consumer fails with "Tried to write the
// same file twice" while TypeScript codegen and the service's own pipeline stay green.
//
// diia-buf-lint passes the descriptors from `buf build proto --exclude-imports` (protojson) and
// prints what this returns, in buf lint's own `path:line:column:message (RULE)` shape.

const RULE = 'JAVA_CLASS_UNIQUE'

/** protoc's UnderscoresToCamelCase(name, true): letters after a separator or a digit go upper case. */
function camelCase(name) {
    let out = ''
    let capNext = true
    for (const ch of name) {
        if (ch >= 'a' && ch <= 'z') {
            out += capNext ? ch.toUpperCase() : ch
            capNext = false
        } else if (ch >= 'A' && ch <= 'Z') {
            out += ch
            capNext = false
        } else if (ch >= '0' && ch <= '9') {
            out += ch
            capNext = true
        } else {
            capNext = true
        }
    }

    return out
}

function typeNames(messages = [], enums = []) {
    return [...enums.map((e) => e.name), ...messages.flatMap((m) => [m.name, ...typeNames(m.nestedType, m.enumType)])]
}

/** The outer class protoc generates for a file, with its "OuterClass" suffix when a type already holds the name. */
export function javaOuterClassName(file) {
    if (file.options?.javaOuterClassname) {
        return file.options.javaOuterClassname
    }

    const base = camelCase(
        file.name
            .split('/')
            .pop()
            .replace(/\.proto$/, ''),
    )
    const taken = new Set([...typeNames(file.messageType, file.enumType), ...(file.service ?? []).map((s) => s.name)])

    return taken.has(base) ? `${base}OuterClass` : base
}

/** Top-level classes a file contributes to its Java package: the outer class, plus each top-level type under java_multiple_files. */
function javaClasses(file) {
    const classes = [javaOuterClassName(file)]
    if (file.options?.javaMultipleFiles) {
        for (const message of file.messageType ?? []) {
            classes.push(message.name, `${message.name}OrBuilder`)
        }
        classes.push(...(file.enumType ?? []).map((e) => e.name))
    }

    return classes
}

/** For a clash between two versions of one file, the name the newer one should take: actions/v4/foo.proto → fooV4.proto. */
function versionedName(paths) {
    const versioned = paths
        .map((path) => ({ path, version: Number(path.match(/(?:^|\/)v(\d+)\//)?.[1]) }))
        .filter(({ version }) => version > 0)
        .sort((a, b) => a.version - b.version)
    if (versioned.length !== paths.length || versioned.length < 2) {
        return undefined
    }

    const newer = versioned.at(-1)
    const file = newer.path
        .split('/')
        .pop()
        .replace(/\.proto$/, '')

    return { path: newer.path, name: `${file}V${newer.version}.proto` }
}

/**
 * @param files FileDescriptorProto objects in protojson form, paths relative to the proto module
 * @param moduleDir the module directory the paths are reported under
 * @returns one buf-lint-style line per file that shares a generated Java class with another file
 */
export function javaClassClashes(files, moduleDir = 'proto') {
    const owners = new Map()
    for (const file of files) {
        const javaPackage = file.options?.javaPackage || file.package || ''
        for (const name of javaClasses(file)) {
            const key = javaPackage ? `${javaPackage}.${name}` : name
            const paths = owners.get(key) ?? []
            if (!paths.includes(file.name)) {
                paths.push(file.name)
            }
            owners.set(key, paths)
        }
    }

    const problems = []
    for (const [javaClass, paths] of owners) {
        if (paths.length < 2) {
            continue
        }

        const rename = versionedName(paths)
        for (const path of paths) {
            const others = paths.filter((other) => other !== path).join(', ')
            const fix =
                rename?.path === path
                    ? `name this file ${rename.name}`
                    : rename
                      ? `rename ${rename.path} to ${rename.name}`
                      : 'rename one of them so the generated classes differ'
            problems.push(`${moduleDir}/${path}:1:1:Java class ${javaClass} is also generated by ${others}; ${fix}. (${RULE})`)
        }
    }

    return problems
}
