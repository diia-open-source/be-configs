import { describe, expect, it } from 'vitest'

import { javaClassClashes, javaOuterClassName } from '../../buf/java-classes.mjs'

describe('diia-buf-lint Java class check', () => {
    it('reports two versions of one file in a package and names the file the newer one should take', () => {
        // Arrange
        const files = [
            { name: 'actions/v3/getMessageById.proto', package: 'ua.gov.diia.notification', messageType: [{ name: 'GetMessageByIdReq' }] },
            {
                name: 'actions/v4/getMessageById.proto',
                package: 'ua.gov.diia.notification',
                messageType: [{ name: 'GetMessageByIdV4Req' }],
            },
        ]

        // Act
        const problems = javaClassClashes(files)

        // Assert
        expect(problems).toEqual([
            'proto/actions/v3/getMessageById.proto:1:1:Java class ua.gov.diia.notification.GetMessageById is also generated by actions/v4/getMessageById.proto; rename actions/v4/getMessageById.proto to getMessageByIdV4.proto. (JAVA_CLASS_UNIQUE)',
            'proto/actions/v4/getMessageById.proto:1:1:Java class ua.gov.diia.notification.GetMessageById is also generated by actions/v3/getMessageById.proto; name this file getMessageByIdV4.proto. (JAVA_CLASS_UNIQUE)',
        ])
    })

    it.each([
        ['the newer file carries its version', 'actions/v4/getMessageByIdV4.proto', {}],
        ['java_package differs', 'actions/v4/getMessageById.proto', { javaPackage: 'ua.gov.diia.notification.v4' }],
        ['java_outer_classname differs', 'actions/v4/getMessageById.proto', { javaOuterClassname: 'GetMessageByIdV4Proto' }],
    ])('passes when %s', (_case, name, options) => {
        // Arrange
        const files = [
            { name: 'actions/v3/getMessageById.proto', package: 'ua.gov.diia.notification' },
            { name, package: 'ua.gov.diia.notification', options },
        ]

        // Act
        const problems = javaClassClashes(files)

        // Assert
        expect(problems).toEqual([])
    })

    it('reports a java_multiple_files message that takes the outer class name of another file', () => {
        // Arrange
        const files = [
            { name: 'types/partner.proto', package: 'ua.gov.diia.partner', messageType: [{ name: 'PartnerData' }] },
            {
                name: 'partner-service.proto',
                package: 'ua.gov.diia.partner',
                options: { javaMultipleFiles: true },
                messageType: [{ name: 'Partner' }],
            },
        ]

        // Act
        const problems = javaClassClashes(files)

        // Assert
        expect(problems).toHaveLength(2)
        expect(problems[0]).toContain(
            'Java class ua.gov.diia.partner.Partner is also generated by partner-service.proto; rename one of them',
        )
    })

    it('ignores a service, which protoc generates no class for', () => {
        // Arrange
        const files = [
            { name: 'types/partner.proto', package: 'ua.gov.diia.partner' },
            {
                name: 'partner-service.proto',
                package: 'ua.gov.diia.partner',
                options: { javaMultipleFiles: true },
                service: [{ name: 'Partner' }],
            },
        ]

        // Act
        const problems = javaClassClashes(files)

        // Assert
        expect(problems).toEqual([])
    })

    it.each([
        ['get_user_info.proto', [], 'GetUserInfo'],
        ['user-v2info.proto', [], 'UserV2Info'],
        ['getUserInfo.proto', [{ name: 'GetUserInfo' }], 'GetUserInfoOuterClass'],
        ['getUserInfo.proto', [{ name: 'Wrapper', nestedType: [{ name: 'GetUserInfo' }] }], 'GetUserInfoOuterClass'],
    ])('names the outer class of %s with types %j as protoc does: %s', (name, messageType, expected) => {
        // Act
        const outer = javaOuterClassName({ name: `actions/v1/${name}`, messageType })

        // Assert
        expect(outer).toBe(expected)
    })
})
